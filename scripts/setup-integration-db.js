// One-time local setup of the dedicated integration database `mawid_test_it`.
//
//   node scripts/setup-integration-db.js            check only (read-only, default)
//   node scripts/setup-integration-db.js --create   create the database + .env.test-it
//
// Safety:
//   - The name is fixed: `mawid_test_it`. No argument can change it.
//   - Uses the credentials of .env.test (the local development account), never .env.
//   - Refuses if `mawid_test_it` already exists and contains anything but Mawid tables, so it can
//     never adopt someone else's database. Never drops, truncates or alters anything.
//   - Only statement that writes: CREATE DATABASE IF NOT EXISTS `mawid_test_it` (utf8mb4).
//   - Writes .env.test-it (git-ignored by `.env.*`) = .env.test with DB_NAME / DATABASE_URL
//     pointing at mawid_test_it. Credentials are never printed.
const fs = require("node:fs");
const path = require("node:path");
const dotenv = require("dotenv");
const mariadb = require("mariadb");

const NAME = "mawid_test_it";
const root = path.join(__dirname, "..");
const sourceEnv = path.join(root, ".env.test");
const targetEnv = path.join(root, ".env.test-it");
const create = process.argv.includes("--create");
const mawidTables = new Set([
    "_prisma_migrations", "users", "events", "registrations", "sessions", "clinics", "clinic_members", "audit_logs",
    "specialties", "services", "doctor_profiles", "doctor_specialties", "doctor_services", "working_hours",
    "schedule_exceptions", "patients", "appointments", "notifications", "auth_tokens", "clinic_invitations", "auth_rate_buckets",
]);

(async () => {
    if (!fs.existsSync(sourceEnv)) throw new Error("Missing .env.test (source of the local credentials).");
    const env = dotenv.parse(fs.readFileSync(sourceEnv));
    const connection = await mariadb.createConnection({ host: env.DB_HOST, port: Number(env.DB_PORT), user: env.DB_USER, password: env.DB_PASSWORD ?? "" });
    try {
        const tables = await connection.query("SELECT table_name AS name FROM information_schema.tables WHERE table_schema = ?", [NAME]);
        const exists = (await connection.query("SELECT COUNT(*) AS n FROM information_schema.schemata WHERE schema_name = ?", [NAME]))[0].n > 0;
        const foreign = tables.map((t) => t.name).filter((name) => !mawidTables.has(name));
        console.log(`${NAME}: ${exists ? `exists (${tables.length} table(s))` : "does not exist"}`);
        if (foreign.length) throw new Error(`${NAME} contains non-Mawid tables (${foreign.join(", ")}). Refusing to touch it.`);
        if (!create) {
            console.log("Check only. Run with --create to create it and write .env.test-it.");
            return;
        }
        if (!exists) {
            await connection.query(`CREATE DATABASE IF NOT EXISTS \`${NAME}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`);
            console.log(`Created database ${NAME}.`);
        }
    } finally {
        await connection.end();
    }

    const url = new URL(env.DATABASE_URL);
    url.pathname = `/${NAME}`;
    const lines = fs.readFileSync(sourceEnv, "utf8").split(/\r?\n/).map((line) => {
        if (/^DB_NAME=/.test(line)) return `DB_NAME=${NAME}`;
        if (/^DATABASE_URL=/.test(line)) return `DATABASE_URL="${url.toString()}"`;
        return line;
    });
    fs.writeFileSync(targetEnv, `# Generated by scripts/setup-integration-db.js — dedicated integration database (emptied by every run).\n${lines.join("\n")}\n`, { mode: 0o600 });
    console.log("Wrote .env.test-it (git-ignored). Next: npm run test:integration");
})().catch((error) => {
    console.error(error.message);
    process.exit(1);
});
